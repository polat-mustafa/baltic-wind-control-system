/**
 * Evidence page — route /evidence.
 *
 * What the platform's models are validated against, with the measured value and the test
 * that checks it. The rows come from src/data/evidence.json, written by the backend
 * validation tests (backend/scripts/build_evidence.py); every test run compares its value
 * with this file, so the page cannot drift from the code.
 *
 * The coverage matrix on top counts the checks per module and kind, and lists the modules
 * that have no external check yet — what is not validated is part of the evidence.
 */

import evidence from "../data/evidence.json";
import { PageHeader } from "../components/layout/PageHeader";
import { GAPS, KINDS, type EvidenceItem, type EvidenceKind } from "../data/evidenceCoverage";

const ITEMS = evidence.items as EvidenceItem[];

const REPO = "https://github.com/polat-mustafa/offshoreforge/blob/main/";

/** Four significant figures, no trailing zeros: 1.043, 318.8, 0.0833. */
function fmt(v: number): string {
  return String(Number(v.toPrecision(4)));
}

export default function EvidencePage() {
  const areas = [...new Set(ITEMS.map((i) => i.area))];
  const count = (area: string, kind: EvidenceKind) => ITEMS.filter((i) => i.area === area && i.kind === kind).length;
  return (
    <div className="space-y-5">
      <PageHeader
        title="Evidence"
        description="What each model is checked against — measured data, independent hand calculations or the reference implementation — with the value it reaches and the test that fails if it gets worse."
        meta={`${ITEMS.length} checks · generated by the backend test suite (scripts/build_evidence.py)`}
      />
      <section aria-label="Coverage" className="overflow-x-auto rounded-lg border border-border-primary bg-bg-secondary p-4">
        <h2 className="mb-2 text-base font-semibold text-text-primary">Coverage by module</h2>
        <table className="w-full min-w-[760px] text-sm">
          <thead className="text-left text-xs text-text-muted">
            <tr>
              <th className="py-1 pr-3 font-medium">Module</th>
              {KINDS.map((k) => (
                <th key={k.id} className="py-1 pr-3 text-right font-medium" title={k.hint}>
                  {k.label}
                </th>
              ))}
            </tr>
          </thead>
          <tbody className="text-text-primary">
            {areas.map((area) => (
              <tr key={area} className="border-t border-border-primary">
                <td className="py-1.5 pr-3">{area}</td>
                {KINDS.map((k) => (
                  <td key={k.id} className="py-1.5 pr-3 text-right font-mono tabular-nums">
                    {count(area, k.id) || <span className="text-text-muted">–</span>}
                  </td>
                ))}
              </tr>
            ))}
            {GAPS.map((g) => (
              <tr key={g.module} className="border-t border-border-primary">
                <td className="py-1.5 pr-3">
                  {g.module} <span className="text-xs text-status-warning">not validated</span>
                </td>
                <td colSpan={KINDS.length} className="py-1.5 pr-3 text-xs text-text-secondary">
                  {g.note}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>
      {areas.map((area) => (
        <section key={area} className="overflow-x-auto rounded-lg border border-border-primary bg-bg-secondary p-4">
          <h2 className="mb-2 text-base font-semibold text-text-primary">{area}</h2>
          <table className="w-full min-w-[760px] text-sm">
            <thead className="text-left text-xs text-text-muted">
              <tr>
                <th className="py-1 pr-3 font-medium">Claim</th>
                <th className="py-1 pr-3 font-medium">Validated against</th>
                <th className="py-1 pr-3 font-medium">Kind</th>
                <th className="py-1 pr-3 font-medium">Metric</th>
                <th className="py-1 pr-3 text-right font-medium">Value</th>
                <th className="py-1 pr-3 font-medium">Acceptance</th>
                <th className="py-1 font-medium">Test</th>
              </tr>
            </thead>
            <tbody className="align-top text-text-primary">
              {ITEMS.filter((i) => i.area === area).map((i) => (
                <tr key={i.id} className="border-t border-border-primary">
                  <td className="py-1.5 pr-3">{i.claim}</td>
                  <td className="py-1.5 pr-3 text-text-secondary">{i.against}</td>
                  <td className="whitespace-nowrap py-1.5 pr-3 text-xs text-text-secondary">
                    {KINDS.find((k) => k.id === i.kind)?.label}
                  </td>
                  <td className="py-1.5 pr-3 text-text-secondary">{i.metric}</td>
                  <td className="whitespace-nowrap py-1.5 pr-3 text-right font-mono tabular-nums">
                    {fmt(i.value)} {i.unit !== "−" && <span className="text-text-muted">{i.unit}</span>}
                  </td>
                  <td className="py-1.5 pr-3 font-mono text-xs text-text-secondary">{i.limit}</td>
                  <td translate="no" className="py-1.5 font-mono text-xs">
                    <a href={REPO + i.test} target="_blank" rel="noreferrer" className="text-accent hover:underline">
                      {i.test.split("/").pop()}
                    </a>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      ))}
      <p className="text-xs text-text-muted">
        Also checked on every run: every SB-510 number quoted in lessons, panels and tours against the backend
        (tests/constants/plantFacts.test.ts), and weekly every cited DOI and link. The ANDES rows run on Linux only
        (CI and the backend Docker image); the GOOSE transfer time is a fixed teaching value, shown against its limit.
      </p>
    </div>
  );
}
